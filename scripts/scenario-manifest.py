#!/usr/bin/env python3
"""Write tests/MANIFEST.md: every scenario, what it needs, and where it runs.

The manifest is generated from the scenarios themselves (the triggers they call
and the requirement they declare), so it cannot drift from the code. Skips are
still recorded at run time by the harness; this file says in advance which ones
can happen and why.

Run: python3 scripts/scenario-manifest.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TRIGGER = re.compile(r"\badrt\s+([A-Z][A-Za-z]+)")
SKIP = re.compile(r'skip\s+"([^"]+)"')
MONITORS = re.compile(r"ADRT_MONITORS=([^\s\"']+)")


def scan(path):
    text = open(path, encoding="utf8").read()
    name = os.path.basename(path).removesuffix(".sh")
    triggers = sorted(set(TRIGGER.findall(text)))
    skips = sorted(set(SKIP.findall(text)))
    needs = []
    if any("four monitors" in reason for reason in skips):
        needs.append("monitor matrix (4 screens)")
    elif "ADRT_MONITORS" in text:
        needs.append("any monitor count")
    if "ydotool" in text:
        needs.append("ydotool")
    if "probe_supports injection" in text:
        needs.append("input injection")
    if "test:client" in text or "TEST_CLIENT" in text:
        needs.append("a test client")
    return name, triggers, skips, needs


def main():
    agent = sorted(f for f in os.listdir(f"{ROOT}/tests/agent") if re.match(r"A\d\d-.*\.sh$", f))
    session = sorted(f for f in os.listdir(f"{ROOT}/tests/session") if re.match(r"S\d\d-.*\.sh$", f))
    rows = []
    for group, files, folder, target in (
        ("agent (nested Shell)", agent, "agent", "headless"),
        ("session (live GNOME)", session, "session", "session"),
    ):
        rows.append(f"\n## {group}\n")
        rows.append("| scenario | runs on | needs | can skip when | triggers |")
        rows.append("| --- | --- | --- | --- | --- |")
        for f in files:
            name, triggers, skips, needs = scan(f"{ROOT}/tests/{folder}/{f}")
            if "monitor matrix (4 screens)" in needs:
                target_note = "headless (4 screens)"
            else:
                target_note = target
            rows.append("| `{name}` | {target} | {needs} | {skips} | {triggers} |".format(
                name=name,
                target=target_note,
                needs=", ".join(needs) or "—",
                skips="; ".join(skips) or "—",
                triggers=", ".join(triggers[:6]) + ("…" if len(triggers) > 6 else ""),
            ))
    doc = f"""# Scenario manifest

Generated by `scripts/scenario-manifest.py` from the scenarios themselves — do not edit
by hand. Skips are recorded at run time by the harness; this is what can be skipped and
why, so no skip is ever a surprise.

Totals: {len(agent)} agent scenarios, {len(session)} session scenarios.

## Where things run (this laptop, 2026-10-01)

| target | state |
| --- | --- |
| `headless` (nested GNOME Shell, `--wayland --headless --no-x11`, virtual monitors) | fully available; 16 workers |
| `headless` with `ADRT_MONITORS` (up to four mixed screens) | available; used by the matrix scenarios |
| `session-like` (isolated `gnome-session` in its own XDG tree) | **not available here** — `gnome-settings-daemon`, `xdg-desktop-portal`, `polkitd` and `gnome-remote-desktop` are not installed |
| `session` (the live GNOME session) | available when the user runs it; the session scenarios only touch their own windows and restore the workspace |
| `ydotool` | never available headlessly (no libinput seat); keybindings use the in-process virtual device instead |
{chr(10).join(rows)}
"""
    with open(f"{ROOT}/tests/MANIFEST.md", "w", encoding="utf8") as f:
        f.write(doc)
    print(f"manifest: {len(agent)} agent + {len(session)} session scenarios")


if __name__ == "__main__":
    main()
