#!/usr/bin/env python3
# Generated with AI for personal use.
# Do NOT upload to extensions.gnome.org (EGO) unless you understand JavaScript
# and can maintain this code.
#
# pot-from-source.py — best-effort gettext template extractor used by
# scripts/update-po.sh when `xgettext` is not installed.
#
# It understands the three call shapes the extension uses:
#     _('msgid')                      gettext()
#     ngettext('one', 'many', n)      ngettext()
#     pgettext('context', 'msgid')    pgettext()
#
# It is *not* a replacement for xgettext (no macro expansion, no JS syntax
# awareness); it only scans literal calls in the files listed in POTFILES.in so
# `npm run i18n:update` still produces a usable template on a stock machine.
#
# Usage: pot-from-source.py <source-file> [<source-file> ...]
# Writes the template to stdout.

import datetime
import re
import sys

CALL_RE = re.compile(r"\b(gettext|ngettext|pgettext|_)\s*\(")


def parse_string_at(text: str, i: int):
    """Parse a JS string literal at `i`; return (value, end) or (None, i)."""
    while i < len(text) and text[i].isspace():
        i += 1
    if i >= len(text) or text[i] not in "'\"":
        return None, i
    quote = text[i]
    i += 1
    out = []
    while i < len(text):
        ch = text[i]
        if ch == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", "\\": "\\",
                        "'": "'", '"': '"', "0": "\0"}.get(nxt, nxt))
            i += 2
            continue
        if ch == quote:
            return "".join(out), i + 1
        out.append(ch)
        i += 1
    return None, i


def call_args(text: str, start: int):
    """Return the string-literal args of the call whose '(' is at `start`."""
    args = []
    i = start + 1
    while i < len(text):
        value, end = parse_string_at(text, i)
        if value is None:
            break
        args.append(value)
        i = end
        while i < len(text) and text[i].isspace():
            i += 1
        if i < len(text) and text[i] == ",":
            i += 1
            continue
        break
    return args


def main(argv):
    entries = {}  # (ctxt, msgid) -> {"plural": str|None, "refs": [str]}

    for path in argv[1:]:
        try:
            with open(path, "r", encoding="utf-8") as handle:
                body = handle.read()
        except OSError as error:
            print("pot-from-source: %s" % error, file=sys.stderr)
            return 1
        for lineno, line in enumerate(body.splitlines(), start=1):
            stripped = line.lstrip()
            if stripped.startswith(("//", "*", "/*")):
                continue
            for match in CALL_RE.finditer(line):
                name = match.group(1)
                args = call_args(line, match.end() - 1)
                ctxt = None
                plural = None
                if name in ("_", "gettext"):
                    if len(args) < 1:
                        continue
                    msgid = args[0]
                elif name == "ngettext":
                    if len(args) < 2:
                        continue
                    msgid, plural = args[0], args[1]
                else:  # pgettext
                    if len(args) < 2:
                        continue
                    ctxt, msgid = args[0], args[1]
                key = (ctxt, msgid)
                entry = entries.setdefault(key, {"plural": None, "refs": []})
                if plural is not None:
                    entry["plural"] = plural
                entry["refs"].append("%s:%d" % (path, lineno))

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M+0000")
    print('# Adrt translation template.')
    print('# This file is generated by `npm run i18n:update`; do not edit it by hand.')
    print('msgid ""')
    print('msgstr ""')
    print('"Project-Id-Version: adrt 0.2.0\\n"')
    print('"Report-Msgid-Bugs-To: \\n"')
    print('"POT-Creation-Date: %s\\n"' % stamp)
    print('"MIME-Version: 1.0\\n"')
    print('"Content-Type: text/plain; charset=UTF-8\\n"')
    print('"Content-Transfer-Encoding: 8bit\\n"')
    print('"Language: \\n"')
    print('"Plural-Forms: nplurals=2; plural=(n != 1);\\n"')
    for (ctxt, msgid), entry in sorted(entries.items(), key=lambda kv: kv[0][1]):
        print("")
        for ref in entry["refs"]:
            print("#: %s" % ref)
        if ctxt is not None:
            print("msgctxt %s" % _quote(ctxt))
        print("msgid %s" % _quote(msgid))
        if entry["plural"] is not None:
            print("msgid_plural %s" % _quote(entry["plural"]))
            print("msgstr[0] \"\"")
            print("msgstr[1] \"\"")
        else:
            print('msgstr ""')
    print("")
    return 0


def _quote(value: str) -> str:
    escaped = (value.replace("\\", "\\\\").replace('"', '\\"')
               .replace("\n", "\\n").replace("\t", "\\t"))
    return '"%s"' % escaped


if __name__ == "__main__":
    sys.exit(main(sys.argv))
