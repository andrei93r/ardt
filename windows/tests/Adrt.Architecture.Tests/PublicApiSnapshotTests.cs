using System.Globalization;
using System.Reflection;
using System.Text;

namespace Adrt.Architecture.Tests;

/// <summary>
/// Freezes the public surface of <c>Adrt.Core</c> so an accidental visibility
/// change (or a method quietly becoming public) shows up as a reviewable diff.
/// The snapshot is generated when missing; once committed the test only compares.
/// </summary>
public sealed class PublicApiSnapshotTests
{
    private const BindingFlags DeclaredPublic =
        BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

    [Fact]
    public void PublicApiMatchesTheCheckedInSnapshot()
    {
        var actual = BuildSnapshot();
        var path = ArchitecturePaths.SnapshotPath;

        var write = Environment.GetEnvironmentVariable("ADRT_UPDATE_API_SNAPSHOT") == "1";
        if (!File.Exists(path) || write)
        {
            File.WriteAllText(path, actual, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            return;
        }

        var expected = File.ReadAllText(path).ReplaceLineEndings("\n");
        Assert.Equal(expected, actual);
    }

    internal static string BuildSnapshot()
    {
        var assembly = typeof(Adrt.Core.JsonLines).Assembly;
        var builder = new StringBuilder();
        builder.Append(
            "# Adrt.Core public API surface.\n" +
            "# Generated by windows/tests/Adrt.Architecture.Tests/PublicApiSnapshotTests.\n" +
            "# Delete this file (or set ADRT_UPDATE_API_SNAPSHOT=1) to regenerate it.\n");

        var types = assembly.GetExportedTypes()
            .OrderBy(type => type.FullName, StringComparer.Ordinal);

        foreach (var type in types)
        {
            builder.Append('\n')
                .Append(Kind(type))
                .Append(' ')
                .Append(TypeName(type))
                .Append('\n');

            var members = DescribeMembers(type)
                .OrderBy(line => line, StringComparer.Ordinal);

            foreach (var member in members)
            {
                builder.Append("  ").Append(member).Append('\n');
            }
        }

        return builder.ToString();
    }

    private static IEnumerable<string> DescribeMembers(Type type)
    {
        foreach (var constructor in type.GetConstructors(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
        {
            yield return $"C:.ctor({Parameters(constructor.GetParameters())})";
        }

        foreach (var method in type.GetMethods(DeclaredPublic))
        {
            // Property/event accessors and the record clone helper are covered by
            // their own lines or are compiler plumbing.
            if ((method.IsSpecialName && !method.Name.StartsWith("op_", StringComparison.Ordinal)) ||
                method.Name.Contains('<'))
            {
                continue;
            }

            var generic = method.IsGenericMethodDefinition
                ? "<" + string.Join(", ", method.GetGenericArguments().Select(argument => argument.Name)) + ">"
                : string.Empty;

            yield return $"{Static(method.IsStatic)}{TypeName(method.ReturnType)} {method.Name}{generic}({Parameters(method.GetParameters())})";
        }

        foreach (var property in type.GetProperties(DeclaredPublic))
        {
            var indexParameters = property.GetIndexParameters();
            var name = indexParameters.Length > 0 ? "this" : property.Name;
            var index = indexParameters.Length > 0 ? $"[{Parameters(indexParameters)}]" : string.Empty;
            var accessors = (property.GetMethod is { IsPublic: true } ? "get; " : string.Empty) +
                            (property.SetMethod is { IsPublic: true } ? "set; " : string.Empty);
            yield return $"P:{Static((property.GetMethod ?? property.SetMethod)!.IsStatic)}{TypeName(property.PropertyType)} {name}{index} {{ {accessors}}}";
        }

        foreach (var field in type.GetFields(DeclaredPublic))
        {
            var modifiers = field.IsLiteral ? "const " : Static(field.IsStatic);
            var value = field.IsLiteral ? " = " + Constant(field.GetRawConstantValue()) : string.Empty;
            yield return $"F:{modifiers}{TypeName(field.FieldType)} {field.Name}{value}";
        }

        foreach (var @event in type.GetEvents(DeclaredPublic))
        {
            yield return $"E:{Static(@event.AddMethod?.IsStatic ?? false)}{TypeName(@event.EventHandlerType!)} {@event.Name}";
        }
    }

    private static string Kind(Type type) =>
        type.IsEnum ? "enum" :
        type.IsInterface ? "interface" :
        typeof(MulticastDelegate).IsAssignableFrom(type.BaseType) ? "delegate" :
        type.IsValueType ? "struct" : "class";

    private static string Static(bool value) => value ? "static " : string.Empty;

    private static string Parameters(ParameterInfo[] parameters) =>
        string.Join(", ", parameters.Select(Parameter));

    private static string Parameter(ParameterInfo parameter)
    {
        var type = parameter.ParameterType;
        var prefix = string.Empty;
        if (type.IsByRef)
        {
            type = type.GetElementType()!;
            prefix = parameter.GetRequiredCustomModifiers().Contains(typeof(System.Runtime.InteropServices.InAttribute))
                ? "in "
                : parameter.IsOut ? "out " : "ref ";
        }
        else if (type.IsArray && parameter.GetCustomAttributes(typeof(ParamArrayAttribute), inherit: false).Length > 0)
        {
            prefix = "params ";
        }

        return prefix + TypeName(type) + " " + parameter.Name;
    }

    private static string TypeName(Type type)
    {
        if (type.IsByRef) return TypeName(type.GetElementType()!) + "&";
        if (type.IsPointer) return TypeName(type.GetElementType()!) + "*";
        if (type.IsArray)
        {
            return TypeName(type.GetElementType()!) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
        }

        if (type.IsGenericParameter) return type.Name;

        var nullable = Nullable.GetUnderlyingType(type);
        if (nullable is not null) return TypeName(nullable) + "?";

        if (type.IsGenericType)
        {
            var definition = type.GetGenericTypeDefinition();
            var name = definition.FullName ?? definition.Name;
            var tick = name.IndexOf('`', StringComparison.Ordinal);
            if (tick >= 0) name = name[..tick];
            return name + "<" + string.Join(", ", type.GetGenericArguments().Select(TypeName)) + ">";
        }

        return type.FullName ?? type.Name;
    }

    private static string Constant(object? value) => value switch
    {
        null => "null",
        string text => "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal) + "\"",
        char character => "'" + character + "'",
        bool flag => flag ? "true" : "false",
        _ => Convert.ToString(value, CultureInfo.InvariantCulture) ?? "null",
    };
}
